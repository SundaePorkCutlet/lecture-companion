// Run explicitly: node test/browser-integration.mjs. Uses only synthetic local pages.
import {createServer} from 'node:http';
import {readFileSync} from 'node:fs';
import {spawn} from 'node:child_process';
const html=readFileSync(new URL('fixtures/player.html',import.meta.url));
let port1,port2;
const serve=(req,res)=>{res.setHeader('Content-Type','text/html; charset=utf-8');
  if(req.url==='/same')res.end(`<iframe id="player" width="700" height="500" src="http://127.0.0.1:${port1}/"></iframe>`);
  else if(req.url==='/cross')res.end(`<iframe id="player" width="700" height="500" src="http://127.0.0.1:${port2}/"></iframe>`);
  else res.end(html);
};
const a=createServer(serve),b=createServer(serve);
await new Promise(r=>a.listen(0,'127.0.0.1',r));port1=a.address().port;
await new Promise(r=>b.listen(0,'127.0.0.1',r));port2=b.address().port;
const moduleURL=new URL('../src/caption-source.mjs',import.meta.url).href;
const script=`
const assert=(await import('node:assert/strict')).default;
const {installCaptionProbe,captionProbeCommand}=await import(${JSON.stringify(moduleURL)});
const task=await taskSpace('Lecture Companion v0.2 verification 20261020');
console.log(JSON.stringify({spaceId:task.spaceId}));
const page=task.page('p1');await page.goto('http://127.0.0.1:${port1}/');
await page.waitForSelector('#caption');
let probe=await page.evaluate(installCaptionProbe,{selector:'#player',captionSelector:'#caption'});
assert.equal(probe.available,true);
await page.evaluate(()=>window.captionSeries(['A','','A','B','C'],25));
let packet=await page.evaluate(captionProbeCommand,{token:probe.token,action:'read'});
assert.deepEqual(packet.events.filter(e=>e.type==='caption').map(e=>e.text),['initial','A','','A','B','C']);
await page.evaluate(captionProbeCommand,{token:probe.token,action:'ack',through:packet.events.at(-1).seq});
assert.equal((await page.evaluate(captionProbeCommand,{token:probe.token,action:'read'})).events.length,0);
await page.evaluate(captionProbeCommand,{token:probe.token,action:'close'});
console.log('PASS: rapid DOM changes, repetition, clear, ack');
probe=await page.evaluate(installCaptionProbe,{selector:'#player',captionSelector:'#caption',capacity:2});
await page.evaluate(()=>window.captionSeries(['overflow1','overflow2','overflow3'],20));
packet=await page.evaluate(captionProbeCommand,{token:probe.token,action:'read'});
assert.ok(packet.dropped>0);assert.equal(packet.events.length,2);
await page.evaluate(captionProbeCommand,{token:probe.token,action:'close'});
console.log('PASS: overflow reported');
await page.evaluate(()=>window.prepareVideo());
probe=await page.evaluate(installCaptionProbe,{selector:'#player'});assert.equal(probe.source,'text-track');
await page.evaluate(async()=>{const v=document.querySelector('video');const ended=new Promise(r=>v.addEventListener('ended',r,{once:true}));await v.play();await ended;});
packet=await page.evaluate(captionProbeCommand,{token:probe.token,action:'read'});
assert.deepEqual(packet.events.filter(e=>e.type==='caption'&&e.text).map(e=>e.text),['cue one','cue two','cue three']);
assert.ok(packet.events.find(e=>e.type==='media-ended'));
assert.ok(packet.events.filter(e=>e.type==='caption').every(e=>Number.isFinite(e.mediaTime)));
await page.evaluate(captionProbeCommand,{token:probe.token,action:'close'});
console.log('PASS: real TextTrack cuechange, media times, ended');
await page.goto('http://127.0.0.1:${port1}/same');await page.waitForSelector('iframe');
await page.waitForFunction(()=>document.querySelector('iframe').contentDocument?.querySelector('#caption'));
probe=await page.evaluate(installCaptionProbe,{selector:'#player',captionSelector:'#caption'});assert.equal(probe.available,true);
await page.evaluate(captionProbeCommand,{token:probe.token,action:'close'});
await page.goto('http://127.0.0.1:${port1}/cross');await page.waitForSelector('iframe');
probe=await page.evaluate(installCaptionProbe,{selector:'#player',captionSelector:'#caption'});assert.deepEqual(probe,{available:false,reason:'cross-origin-frame'});
console.log('PASS: same-origin iframe and explicit cross-origin boundary');
await task.finish({keep:[]});
`;
try{
  const child=spawn('ego-browser',['nodejs'],{stdio:['pipe','inherit','inherit']});child.stdin.end(script);
  const result=await new Promise((resolve,reject)=>{child.on('error',reject);child.on('exit',resolve);});
  process.exitCode=result??1;
}finally{a.close();b.close();}
